"""Write docs/text_unshown.tsv: script rows the game never draws in play, with the reason (textcover.py --waive).

    python -X utf8 tools/gen_waivers.py [--check]

Waived: rows noted nontext/debug/placeholder (tools/notes.py), and every row of the sub-tables whose master entry
no loader call ever read over the full scene tour (s00 enemy names, s04, s05 stage-clear list, s06 mission text:
docs/re/scenes.md §Event scripts and the message viewer). --check exits 1 when the file is out of date.
"""
import argparse
import csv
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'text_unshown.tsv')
UNREAD = {
    's00': 'master entry 1 never read by the loader in the 75-scene tour (enemy name list, no reader found)',
    's04': 'master entry 6 never read by the loader in the 75-scene tour (no reader found)',
    's05': 'master entry 7 never read by the loader in the 75-scene tour (stage-clear list, no reader found)',
    's06': 'master entry 8 never read by the loader in the 75-scene tour (mission text, no reader found)',
}


def rows():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'script', 's*.tsv'))):
        t = os.path.basename(path)[:3]
        with open(path, encoding='utf-8', newline='') as f:
            for row in csv.DictReader(f, delimiter='\t', quoting=csv.QUOTE_NONE):
                m = re.match(r'(nontext|debug|placeholder):\s*(.*)', row.get('notes') or '')
                if t in UNREAD:
                    out.append((row['id'], '%s: %s' % (t, UNREAD[t])))
                elif m:
                    out.append((row['id'], '%s: %s' % (m.group(1), m.group(2) or 'not drawn in play')))
    return out


def render():
    lines = ['# Script rows accepted as never drawn in play (generated by tools/gen_waivers.py; textcover.py --waive).']
    lines += ['%s\t%s' % r for r in rows()]
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = render()
    if a.check:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        sys.exit(0 if cur == text else 'docs/text_unshown.tsv is out of date: run tools/gen_waivers.py')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('%d waivers -> %s' % (text.count('\n') - 1, OUT))


if __name__ == '__main__':
    main()
